class SVG:
    def __init__(self, w, h):
        self.w, self.h, self.parts = w, h, []

    def rect(self, x, y, w, h, color):
        self.parts.append(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" fill="{C.get(color, color)}"/>')
        return self

    def poly(self, points, color):
        pts = " ".join(f"{x},{y}" for x, y in points)
        self.parts.append(f'<polygon points="{pts}" fill="{C.get(color, color)}"/>')
        return self

    def star(self, x, y, color="cream", size=4):
        self.rect(x-size, y, size*3, size, color)
        self.rect(x, y-size, size, size*3, color)

    def save(self, name):
        (ART / f"{name}.svg").write_text(
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{self.w}" height="{self.h}" viewBox="0 0 {self.w} {self.h}" shape-rendering="crispEdges">\n'
            + "\n".join(self.parts) + "\n</svg>\n"
        )


